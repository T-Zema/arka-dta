# Zerg vehicles (Overlord, Mutalisk, Scourge, Guardian, Devourer, Queen, drones, Lurker, heroes, upgraded units) play their
# StarCraft death sound. Vehicles ignore DieSound= (wiki workflow/known-mistakes); a vehicle's death sound is the Report= of
# its Explosion= animation. The Zerg generators gave them Explosion=FBALL1, so they died with the fireball's sound instead
# (user test 2026-10-27: the Overlord sounded like a destroyed building). Same pattern as the Protoss (SCPPDTHX...).
# For every vehicle in [VehicleTypes] of the faction map code whose ID starts with SCZ and that has DieSound=X, this writes
#   - Art.ini, block "; >>> Zerg death sounds": [ZDTH_X] Image=FBALL1 (same picture as before) with Report=X
#   - map code layer "Zerg death sounds" (INI/Map Code/SC Factions, above the Zerg layers, so its keys win over them):
#     [Animations] ZDA<nn>=ZDTH_X and [<unit>] Explosion=ZDTH_X / ScrapExplosion=ZDTH_X
# Buildings are left alone (they play DieSound themselves). Re-run after build-sczergbase.ps1 / build-sczergresearch.ps1 /
# build-sczergheroes.ps1 -Install (new Zerg vehicles); re-running replaces its own blocks. Wiki: mods/zerg-faction.
# Usage: build-sczergdeath.ps1 [-WhatIf]
param([switch]$WhatIf)
$ErrorActionPreference = 'Stop'
$game = (Resolve-Path "$PSScriptRoot\..\..").Path
. "$PSScriptRoot\MapCode.ps1"
$faction = Get-MapCodeLayer 'Zerg death sounds'; $art = "$game\INI\Art.ini"; $sound = "$game\INI\Sound.ini"
$latin = [Text.Encoding]::GetEncoding(28591)
$begin = '; >>> Zerg death sounds'; $end = '; <<< Zerg death sounds'

function Backup([string]$path) { if (-not (Test-Path "$path.bak")) { Copy-Item $path "$path.bak" } }
function Nl([string]$path) { if ([IO.File]::ReadAllText($path, $latin).Contains("`r`n")) { "`r`n" } else { "`n" } }
function Set-Block([string]$path, [string]$body) {
    $nl = Nl $path
    $t = [IO.File]::ReadAllText($path, $latin)
    $block = ($begin + $nl + ($body.TrimEnd() -replace "`r?`n", $nl) + $nl + $end + $nl)
    $a = $t.IndexOf($begin)
    if ($a -ge 0) { $b = $t.IndexOf($end, $a); $b = $t.IndexOf("`n", $b) + 1; $t = $t.Substring(0, $a) + $block + $t.Substring($b) }
    else { if (-not $t.EndsWith("`n")) { $t += $nl }; $t += $nl + $block }
    [IO.File]::WriteAllText($path, $t, $latin)
}
# section -> key -> value (repeated sections merged, later key wins, as the client does), ignoring this script's own block
function Read-Sections([string]$path, [string]$text) {
    $t = if ($path) { [IO.File]::ReadAllText($path, $latin) } else { $text }; $a = $t.IndexOf($begin)
    if ($a -ge 0) { $b = $t.IndexOf("`n", $t.IndexOf($end, $a)) + 1; $t = $t.Substring(0, $a) + $t.Substring($b) }
    $d = @{}; $sec = $null
    foreach ($l in ($t -split "`r?`n")) {
        if ($l -match '^\[([^\]]+)\]') { $sec = $Matches[1]; if (-not $d.ContainsKey($sec)) { $d[$sec] = [ordered]@{} }; continue }
        if ($sec -and $l -match '^\s*([A-Za-z0-9_]+)\s*=\s*([^;\t]*)') { $d[$sec][$Matches[1]] = $Matches[2].Trim() }
    }
    return $d
}

$ini = Read-Sections -text (Read-MapCodeText -Exclude $faction)
$snd = Read-Sections $sound
$units = @($ini['VehicleTypes'].Values | Where-Object { $_ -like 'SCZ*' } | Select-Object -Unique)
$anims = [ordered]@{}   # sound -> anim
$rows = @()
foreach ($u in $units) {
    if (-not $ini.ContainsKey($u)) { continue }
    $die = $ini[$u]['DieSound']
    if (-not $die) { continue }
    if (-not $snd.ContainsKey($die)) { throw "[$u] DieSound=$die is not in Sound.ini" }
    if (-not $anims.Contains($die)) { $anims[$die] = "ZDTH_$die" }
    $rows += [pscustomobject]@{ Unit = $u; Sound = $die; Anim = $anims[$die]; Was = $ini[$u]['Explosion'] }
}
if ($rows.Count -eq 0) { throw "no Zerg vehicles with DieSound= found" }

$fb = New-Object Text.StringBuilder
[void]$fb.AppendLine('; Generated by Modding/tools/build-sczergdeath.ps1: vehicles ignore DieSound=, so each Zerg vehicle gets an Explosion=')
[void]$fb.AppendLine('; animation (Art.ini, same block name) whose Report= is its SC death sound. Re-run after the Zerg generators.')
[void]$fb.AppendLine('[Animations]')
$i = 1; foreach ($s in $anims.Keys) { [void]$fb.AppendLine(('ZDA{0:D2}={1}' -f $i, $anims[$s])); $i++ }
foreach ($r in $rows) { [void]$fb.AppendLine(''); [void]$fb.AppendLine("[$($r.Unit)]"); [void]$fb.AppendLine("Explosion=$($r.Anim)"); [void]$fb.AppendLine("ScrapExplosion=$($r.Anim)") }

$ab = New-Object Text.StringBuilder
[void]$ab.AppendLine('; Generated by Modding/tools/build-sczergdeath.ps1: fireball picture, SC death sound (Zerg vehicles).')
foreach ($s in $anims.Keys) {
    [void]$ab.AppendLine(''); [void]$ab.AppendLine("[$($anims[$s])]")
    foreach ($l in 'Image=FBALL1', 'Normalized=yes', 'UseNormalLight=yes', 'Scorch=yes', 'Next=SMOKE_M', "Report=$s") { [void]$ab.AppendLine($l) }
}

$rows | Format-Table Unit, Sound, Anim, Was -AutoSize | Out-String -Width 200
if ($WhatIf) { $fb.ToString(); $ab.ToString(); return }
if (Get-Process -Name game -ErrorAction SilentlyContinue) { throw "game.exe is running: close the game first" }
Backup $faction; Backup $art
Set-Block $faction $fb.ToString()
Set-Block $art $ab.ToString()
"written: $($rows.Count) vehicles, $($anims.Count) animations ($(Split-Path $faction -Leaf) + Art.ini, block '$begin')"
